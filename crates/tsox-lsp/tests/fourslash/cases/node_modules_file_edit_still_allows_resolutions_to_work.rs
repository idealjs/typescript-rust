use tsox_lsp::fourslash::{self, Session};


#[ignore = "unimplemented: fourslash.VerifySuggestionDiagnostics"]
#[test]
fn node_modules_file_edit_still_allows_resolutions_to_work() {
    let content = r##"// @Filename: /tsconfig.json
{ "compilerOptions": { "module": "nodenext", "strict": true } }
// @Filename: /package.json
{ "type": "module", "imports": { "#foo": "./foo.cjs" } }
// @Filename: /foo.cts
export const x = 1;
// @Filename: /index.ts
import * as mod from "#foo";
/**/"##;
    let mut s = Session::new_for_test("nodeModulesFileEditStillAllowsResolutionsToWork", content);
    fourslash::go_to_marker(&mut s, "");
    fourslash::insert(&mut s, "mod.x");
    fourslash::verify_no_errors(&mut s, );
    fourslash::unsupported("VerifySuggestionDiagnostics"); // f.VerifySuggestionDiagnostics(t, nil)
}
