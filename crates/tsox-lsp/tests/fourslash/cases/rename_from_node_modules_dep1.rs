use tsox_lsp::fourslash::{self, Session};

#[ignore = "unimplemented: fourslash.VerifyRenameFailed"]
#[test]
fn rename_from_node_modules_dep1() {
    let content = r#"// @Filename: /index.ts
import { /*okWithAlias*/[|Foo|] } from "foo";
declare const f: Foo;
f./*notOk*/bar;
// @Filename: /tsconfig.json
 { }
// @Filename: /node_modules/foo/package.json
 { "types": "index.d.ts" }
// @Filename: /node_modules/foo/index.d.ts
export interface Foo {
    bar: string;
}"#;
    let mut s = Session::new(content);
    fourslash::go_to_marker(&mut s, "okWithAlias");
    fourslash::unsupported("VerifyRenameSucceeded"); // f.VerifyRenameSucceeded(t, &lsutil.UserPreferences{UseAliasesForRename: core.TSTrue})
    fourslash::unsupported("VerifyRenameFailed"); // f.VerifyRenameFailed(t, &lsutil.UserPreferences{UseAliasesForRename: core.TSFalse})
    fourslash::go_to_marker(&mut s, "notOk");
    fourslash::unsupported("VerifyRenameFailed"); // f.VerifyRenameFailed(t, nil /*preferences*/)
}
