use tsox_lsp::fourslash::{self, Session};

#[ignore = "unimplemented: fourslash.VerifyRenameFailed"]
#[test]
fn rename_from_node_modules_dep4() {
    let content = r#"// @Filename: /index.ts
import hljs from "highlight.js/lib/core"
import { h } from "highlight.js/lib/core";
import { /*notOk*/h as hh } from "highlight.js/lib/core";
/*ok*/[|hljs|];
/*okWithAlias*/[|h|];
/*ok2*/[|hh|];
// @Filename: /node_modules/highlight.js/lib/core.d.ts
declare const hljs: { registerLanguage(s: string): void };
export default hljs;
export const h: string;
// @Filename: /tsconfig.json
{}"#;
    let mut s = Session::new(content);
    fourslash::go_to_marker(&mut s, "ok");
    fourslash::unsupported("VerifyRenameSucceeded"); // f.VerifyRenameSucceeded(t, &lsutil.UserPreferences{UseAliasesForRename: core.TSTrue})
    fourslash::unsupported("VerifyRenameSucceeded"); // f.VerifyRenameSucceeded(t, &lsutil.UserPreferences{UseAliasesForRename: core.TSFalse})
    fourslash::go_to_marker(&mut s, "ok2");
    fourslash::unsupported("VerifyRenameSucceeded"); // f.VerifyRenameSucceeded(t, &lsutil.UserPreferences{UseAliasesForRename: core.TSTrue})
    fourslash::unsupported("VerifyRenameSucceeded"); // f.VerifyRenameSucceeded(t, &lsutil.UserPreferences{UseAliasesForRename: core.TSFalse})
    fourslash::go_to_marker(&mut s, "notOk");
    fourslash::unsupported("VerifyRenameFailed"); // f.VerifyRenameFailed(t, &lsutil.UserPreferences{UseAliasesForRename: core.TSTrue})
    fourslash::unsupported("VerifyRenameFailed"); // f.VerifyRenameFailed(t, &lsutil.UserPreferences{UseAliasesForRename: core.TSFalse})
    fourslash::go_to_marker(&mut s, "okWithAlias");
    fourslash::unsupported("VerifyRenameSucceeded"); // f.VerifyRenameSucceeded(t, &lsutil.UserPreferences{UseAliasesForRename: core.TSTrue})
    fourslash::unsupported("VerifyRenameFailed"); // f.VerifyRenameFailed(t, &lsutil.UserPreferences{UseAliasesForRename: core.TSFalse})
}
